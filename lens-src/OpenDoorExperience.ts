      const target=this.spatial.makeSpatialTarget('Layout option '+(index+1),reserveLabel(proposal.certifiedReserveM,index),()=>this.selectRepair(index),13,6,proposal.id);
      this.spatial.setTargetColor('Layout option '+(index+1),this.proposalColor(index));
      const world=this.roomRoot.getTransform().getWorldTransform().multiplyPoint(this.point(move.to.x,move.to.y,object.height));
      const right=this.camera?this.camera.right:vec3.right();
      target.getTransform().setWorldPosition(world.add(right.uniformScale((index-(this.repairProposals.length-1)/2)*15)).add(new vec3(0,9,0)));
      target.enabled=!this.repairSolo;if(camera)this.spatial.face(target,camera);
