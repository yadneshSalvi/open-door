  private commitMove(id:string,x:number,y:number,theta?:number) {
    const prior=this.input.room.objects.find((o:any)=>o.id===id);
    if(prior&&Math.hypot(prior.pose.x-x,prior.pose.y-y)<1e-6&&Math.abs(Core.normalizeAngle(prior.pose.theta-(theta??prior.pose.theta)))<1e-6)return;
    const next=Core.moveObject(this.input.room,id,x,y,theta);
    if(next===this.input.room){const object=this.input.room.objects.find((o:any)=>o.id===id);this.present(object&&object.locked?object.name+' is locked.':Core.placementIssue(this.input.room,id,x,y,theta)||'No change to this piece.');this.audio.play('contact',(this.furnitureRoots[id]||this.player).getTransform().getWorldPosition());return;}
    const moved=next.objects.find((object:any)=>object.id===id);
    if(Core.objectPolygon(moved).some((p:any)=>p.x<0||p.y<0||p.x>next.width||p.y>next.depth)) {
      this.present('That edit crosses the room boundary. Choose another position.');return;
    }
    this.history.push(this.copy(this.input));this.input.room=next;this.evaluateCurrent();
    this.undoObject=id;this.undoUntil=getTime()+5;this.afterDragFeedback=true;this.firstDrag=false;this.hints?.dismiss();
  }
