  /** Evaluate the whole dock/readout against projected model parts before moving it. */
  private safeMiniatureDock(preferred:vec3,camera:vec3,profileMode:boolean):vec3|null {
    if(!this.camera)return preferred;
    const key=this.generation+'|'+this.menu+'|'+profileMode+'|'+this.repairIndex+'|'+this.repairPreview+'|'+this.spatial.actionLabels().length,cache=this.safeDockCache,direction=this.camera.forward;
    if(cache&&cache.key===key&&camera.distance(cache.camera)<2&&direction.sub(cache.direction).length<.0349)return cache.position;
    const provider=WorldCameraFinderProvider.getInstance();if(typeof provider.worldSpaceToScreenSpace!=='function')return preferred;
    const project=(p:{x:number;y:number;z:number})=>provider.worldSpaceToScreenSpace(p.x,p.y,p.z);
    const boxes=this.projectedSubjects(true).map(item=>annotationBounds(item.points.map(project))).filter((box):box is AnnotationBox=>Boolean(box));
    const frame=annotationFrame(camera,preferred);if(!frame)return null;
    const right=new vec3(frame.right.x,frame.right.y,frame.right.z),up=new vec3(frame.up.x,frame.up.y,frame.up.z);
    const count=this.spatial.actionLabels().length,width=Math.max(10.5,count*10.5+Math.max(0,count-1)*2.2)+.6,top=3.4;
    let position:vec3|null=null;
    // Prefer the near edge; a bounded upper or side slot is a genuine fallback.
    // Never silently use the overlapping preferred pose when all slots fail.
    for(const y of [0,-2,-4,-6,-8,-10,-12,6,10,14,18,22,26,30]){
      for(const x of [0,-4,4]){
        const at=preferred.add(up.uniformScale(y)).add(right.uniformScale(x)),center=at.add(up.uniformScale((top-3.4)/2));
        const box=projectedPlate(center,camera,width,top+3.4,project);
        if(box&&box.left>=.015&&box.right<=.985&&box.top>=.015&&box.bottom<=.985&&!boxes.some(other=>annotationsOverlap(box,other))){position=at;break;}
      }
      if(position)break;
    }
    this.dockLayoutStatus=position?'placed':'no clear projected slot';
    this.safeDockCache={key,camera:new vec3(camera.x,camera.y,camera.z),direction:new vec3(direction.x,direction.y,direction.z),position};return position;
  }
  private updateDock(camera:vec3|null,profileMode:boolean) {
    const dock=this.spatial.dock;
    if(this.menu==='placement'&&camera&&this.camera){
      this.spatial.setDockVertical(false);this.spatial.setDockVisible(true);
      const desired=camera.add(this.camera.forward.uniformScale(-1).normalize().uniformScale(65)).sub(this.camera.up.uniformScale(8));
      dock.getTransform().setWorldPosition(vec3.lerp(dock.getTransform().getWorldPosition(),desired,Math.min(1,Math.max(0,getDeltaTime())*7)));
      dock.getTransform().setWorldScale(vec3.one());this.spatial.face(dock,camera);return;
    }
    if(this.miniature) {
      this.spatial.setDockVertical(false);
      const localCamera=camera?this.roomRoot.getTransform().getInvertedWorldTransform().multiplyPoint(camera):new vec3(0,0,1);
      const direction=new vec3(localCamera.x,0,localCamera.z),length=Math.hypot(direction.x,direction.z);
      const dx=length>.001?direction.x/length:0,dz=length>.001?direction.z/length:1;
      const radius=Math.min((this.input.room.width*50+70)/Math.max(.001,Math.abs(dx)),(this.input.room.depth*50+70)/Math.max(.001,Math.abs(dz)));
      let world=this.roomRoot.getTransform().getWorldTransform().multiplyPoint(new vec3(dx*radius,40,dz*radius));
      if(camera){const safe=this.safeMiniatureDock(world,camera,profileMode);if(!safe){this.spatial.setDockVisible(false,true);return;}world=safe;}
      this.spatial.setDockVisible(!(this.band==='far'&&this.menu==='overview'));
      if(!this.dockSettled){dock.getTransform().setWorldPosition(world);this.dockSettled=true;}
      else if(!this.drag&&!this.spatial.dockHovered())dock.getTransform().setWorldPosition(vec3.lerp(dock.getTransform().getWorldPosition(),world,Math.min(1,Math.max(0,getDeltaTime())*7)));
      dock.getTransform().setWorldScale(vec3.one());
      if(camera)this.spatial.face(dock,camera);
    }else if(camera&&this.camera) {
      const rejectKey=this.generation+'|'+this.menu+'|'+this.spatial.actionLabels().length,rejected=this.fullDockRejected;
      if(rejected&&rejected.key===rejectKey&&camera.distance(rejected.camera)<2&&this.camera.forward.sub(rejected.direction).length<.0349){this.dockLayoutStatus='no clear projected slot';this.spatial.setDockVisible(false,true);return;}
      const provider=WorldCameraFinderProvider.getInstance(),project=(p:{x:number;y:number;z:number})=>provider.worldSpaceToScreenSpace(p.x,p.y,p.z);
      const copy=(p:vec3)=>({x:p.x,y:p.y,z:p.z}),frame={right:copy(this.camera.right),up:copy(this.camera.up),normal:copy(this.camera.forward)};
      const subjects=this.projectedSubjects(true).map(item=>annotationBounds(item.points.map(project))).filter((b):b is AnnotationBox=>Boolean(b));
      const count=this.spatial.actionLabels().length;
      const choice=chooseFullSizeDock(copy(camera),copy(this.camera.forward.uniformScale(-1)),frame,this.patchEdges(camera).map(copy),count,project,subjects,this.dockSettled?this.fullDockChoice:null);
      this.fullDockChoice=choice;
      if(!choice){this.fullDockRejected={key:rejectKey,camera:new vec3(camera.x,camera.y,camera.z),direction:new vec3(this.camera.forward.x,this.camera.forward.y,this.camera.forward.z)};this.dockLayoutStatus='no clear projected slot';this.spatial.setDockVisible(false,true);return;}
      this.fullDockRejected=null;
      const desired=new vec3(choice.position.x,choice.position.y,choice.position.z),current=dock.getTransform().getWorldPosition();
      this.spatial.setDockVertical(choice.vertical);
      if(!this.dockSettled){dock.getTransform().setWorldPosition(desired);this.dockSettled=true;}
      else if(!this.drag&&!this.spatial.dockHovered()){
        const distance=current.distance(desired);
        if(distance>3)this.dockFollowing=true;
        if(distance<3)this.dockFollowing=false;
        const delta=Math.max(0,Math.min(.05,getDeltaTime()));
        if(this.dockFollowing)dock.getTransform().setWorldPosition(vec3.lerp(current,desired,Math.min(1,delta*2.2,45*delta/Math.max(.001,distance))));
      }
      dock.getTransform().setWorldScale(vec3.one().uniformScale(choice.scale));
      dock.getTransform().setWorldRotation(quat.lookAt(this.camera.forward,this.camera.up));
      const actual={...choice,position:copy(dock.getTransform().getWorldPosition())},safe=safeDockPose(actual,count,frame,project,subjects);
      const settled=dock.getTransform().getWorldPosition().distance(desired)<3;
      this.dockLayoutStatus=safe&&settled?'placed · '+choice.mode:'moving to clear patch edge';
      this.spatial.setDockVisible(safe&&settled,!safe);
    }
  }
