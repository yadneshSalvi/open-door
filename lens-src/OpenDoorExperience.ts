  private flushFurnitureDrag() {
    const pending = this.pendingDragCommit;
    if (!pending) return;
    this.pendingDragCommit = null;
    if (pending.generation !== this.generation) {
      this.renderRoom();
      this.present();
      return;
    }
    const object = this.input.room.objects.find((item) => item.id === pending.id);
    const issue = !object || object.locked ? "The selected piece is locked." : Core.placementIssue(this.input.room, pending.id, pending.x, pending.y, pending.theta);
    if (issue) {
      this.renderRoom();
      this.present("Move cancelled. " + issue);
      this.audio.play('contact',pending.root.getTransform().getWorldPosition());
      return;
    }
    if (Math.hypot(pending.x - object.pose.x, pending.y - object.pose.y) < 1e-5) {
      this.renderRoom();
      this.present();
      return;
    }
    this.commitMove(pending.id, pending.x, pending.y, pending.theta);
  }
