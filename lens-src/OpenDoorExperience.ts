  /** Project a SIK world ray into the actual tilted/scaled model floor frame. */
  private floorRayPoint(event:InteractorEvent): {x:number;y:number} | null {
    const start=event.interactor.startPoint,direction=event.interactor.direction;
    if(!start)return null;
    const inverse=this.roomRoot.getTransform().getInvertedWorldTransform();
    if(event.interactor.activeTargetingMode===TargetingMode.Direct){
      const local=inverse.multiplyPoint(start);
      return {x:local.x/100+this.input.room.width/2,y:-local.z/100+this.input.room.depth/2};
    }
    if(!direction)return null;
    const origin = inverse.multiplyPoint(start);
    const end = inverse.multiplyPoint(new vec3(start.x + direction.x, start.y + direction.y, start.z + direction.z));
    const dy = end.y - origin.y;
    if (Math.abs(dy) < 1e-7) return null;
    const t = -origin.y / dy;
    if (t < 0 || !Number.isFinite(t)) return null;
    return {
      x: (origin.x + (end.x - origin.x) * t) / 100 + this.input.room.width / 2,
      y: -(origin.z + (end.z - origin.z) * t) / 100 + this.input.room.depth / 2
    };
  }
  private beginFurnitureDrag(object:any, root:SceneObject, event:InteractorEvent) {
    if(this.drag||this.pendingDragCommit||this.evaluationJob||this.repairProposals.length)return;
    if(this.repairJob||this.repairRequest){this.resetRepair();this.menu='overview';this.updateActions();}
    event.stopPropagation();
    this.selectedObject = object.id;
    const current = this.input.room.objects.find((item) => item.id === object.id);
    if (!current || !current.movable || current.locked) {
      this.present((current?current.name:'This piece')+' is locked.');
      return;
    }
    const point = this.floorRayPoint(event);
    if (!point) {
      this.present("Aim the furniture ray toward the floor to begin moving.");
      return;
    }
    this.playing=false;this.audio.stop();this.firstDrag=false;this.focusUntil=getTime()+3;
    this.drag = {
      id: object.id,
      root,
      interactor: event.interactor,
      generation: this.generation,
      original: { ...current.pose },
      offsetX: point.x - current.pose.x,
      offsetY: point.y - current.pose.y,
      x: current.pose.x,
      y: current.pose.y
    };
    this.routeRoot.enabled = false;
    this.updateSpatialState();
  }
  private previewFurnitureDrag(event:InteractorEvent) {
    const drag = this.drag;
    if (!drag || drag.interactor !== event.interactor || drag.generation !== this.generation) return;
    event.stopPropagation();
    const point = this.floorRayPoint(event);
    if (!point) return;
    drag.x = point.x - drag.offsetX;
    drag.y = point.y - drag.offsetY;
    drag.root.getTransform().setLocalPosition(this.point(drag.x, drag.y, 0));
    const issue = Core.placementIssue(this.input.room, drag.id, drag.x, drag.y, drag.original.theta);
    this.setHalo(drag.id,issue?C.amber:C.mint,issue?'evidence-invalid':'evidence-valid');
  }
  private finishFurnitureDrag(event:InteractorEvent) {
    const drag = this.drag;
    if (!drag || drag.interactor !== event.interactor) return;
    this.previewFurnitureDrag(event);
    event.stopPropagation();
    this.pendingDragCommit = { id: drag.id, root: drag.root, x: drag.x, y: drag.y, theta: drag.original.theta, generation: drag.generation };
    this.drag = null;
  }
  private cancelFurnitureDrag() {
    if (this.drag) {
      this.drag.root.getTransform().setLocalPosition(this.point(this.drag.original.x, this.drag.original.y, 0));
      this.drag = null;
    }
    if (this.pendingDragCommit) {
      const original = this.input.room.objects.find((item) => item.id === this.pendingDragCommit.id);
      if (original) this.pendingDragCommit.root.getTransform().setLocalPosition(this.point(original.pose.x, original.pose.y, 0));
    }
    this.pendingDragCommit = null;
    if (this.routeRoot) this.routeRoot.enabled = true;

  }
  private flushFurnitureDrag() {
    const pending = this.pendingDragCommit;
    if (!pending) return;
    this.pendingDragCommit = null;
    if (pending.generation !== this.generation) {
      this.renderRoom();
      this.present();
      return;
    }
    const object = this.input.room.objects.find((item) => item.id === pending.id);
    const issue = !object || object.locked ? "The selected piece is locked." : Core.placementIssue(this.input.room, pending.id, pending.x, pending.y, pending.theta);
    if (issue) {
      this.renderRoom();
      this.present("Move cancelled. " + issue);
      return;
    }
    if (Math.hypot(pending.x - object.pose.x, pending.y - object.pose.y) < 1e-5) {
      this.renderRoom();
      this.present();
      return;
    }
    this.commitMove(pending.id, pending.x, pending.y, pending.theta);
  }
