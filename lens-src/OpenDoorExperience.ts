  public play() {
    if(this.evaluationJob||this.currentRevision!==this.input.room.revision){this.resumeAfterEvaluation=true;return;}
    if(!this.profileReviewed){this.pendingReplay=true;this.showMenu('profileConfirm');return;}
    const task=this.result.tasks[this.selected];
    if(task.status!=='verified_feasible') {
      this.renderRoom();
      // A witness is a checked pose, not a verified route to that pose.
      if(task.witness&&this.selected==='journey'){this.setPose(this.player,task.witness.pose);this.playerPose=task.witness.pose;}
      this.statusUntil=getTime()+3;this.statusNote=task.status==='no_path_found'?'No route found within this search':'';
      const obstacle=task.witness&&this.furnitureRoots[task.witness.objectId];
      this.audio.play('contact',(obstacle||this.player).getTransform().getWorldPosition());this.present();return;
    }
    this.playbackGeneration=this.generation;this.playbackStart=getTime();this.playing=true;this.wheelAngle=0;
    this.lastPlaybackPose=null;this.menu='playing';this.updateActions();
    this.audio.play('roll',this.player.getTransform().getWorldPosition());
  }
  private update() {
    if(!this.input||!this.spatial)return;
    const surfaceStatus=this.surface.status;this.surface.update();
    if(this.menu==='placement'&&(surfaceStatus!==this.surface.status||this.surface.status==='ready'))this.updateActions();
    this.flushFurnitureDrag();this.stepEvaluation();this.updateSpatialState();
    if(this.pendingRepairApply){this.pendingRepairApply=false;this.applyRepair();}
    if(this.repairRequest){
      const request=this.repairRequest;
      if(!this.requestIsCurrent(request)){this.cancelRepair();return;}
      this.repairMetrics.elapsedSeconds=getTime()-this.repairStartedAt;
      if(this.repairMetrics.elapsedSeconds>25){this.failRepair('Online search timed out','timed_out');return;}
      if(request.response)this.verifyNextRemoteProposal(request);
      else if(getTime()-this.repairStatusAt>.12){this.repairStatusAt=getTime();this.present();}
    }
    if(this.repairJob){
      if(this.repairGeneration!==this.generation||this.repairProgress.sourceHash!==Core.stableHash(this.input)){this.cancelRepair();return;}
      const tickStarted=Date.now();this.repairProgress=this.repairJob.step(6);
      this.repairMetrics.steps++;this.repairMetrics.maxStepMs=Math.max(this.repairMetrics.maxStepMs,Date.now()-tickStarted);this.repairMetrics.elapsedSeconds=getTime()-this.repairStartedAt;
      if(this.repairProgress.status!=='searching'){
        this.repairTransport='offline_complete';this.finishRepair();
      }else if(getTime()-this.repairStatusAt>.12){this.repairStatusAt=getTime();this.present();}
    }
    if(!this.playing||this.playbackGeneration!==this.generation)return;
    const path=this.result.tasks[this.selected].path;
    if(!Array.isArray(path)||!path.length){this.playing=false;return;}
    // These are the core's sampled constant-curvature trajectories, not a new visual route.
    const elapsed=getTime()-this.playbackStart;
    const index=Math.min(path.length-1,Math.floor((Number.isFinite(elapsed)?Math.max(0,elapsed):0)*12));
    const pose=path[index]||path[0];
    if(!pose){this.playing=false;return;}
    if(this.selected==='journey'){
      this.setPose(this.player,pose);this.playerPose=pose;
      if(this.lastPlaybackPose){const dx=pose.x-this.lastPlaybackPose.x,dy=pose.y-this.lastPlaybackPose.y;this.wheelAngle+=(dx*Math.cos(pose.theta)+dy*Math.sin(pose.theta))/Math.min(this.input.profile.length*.25,this.input.profile.height*.25);}
      for(const wheel of this.chairWheels)wheel.getTransform().setLocalRotation(quat.angleAxis(this.wheelAngle,vec3.forward()).multiply(quat.angleAxis(Math.PI/2,vec3.right())));
      this.lastPlaybackPose=pose;this.audio.follow(this.player.getTransform().getWorldPosition());
    }else this.doorRoot.getTransform().setLocalRotation(quat.angleAxis(pose.theta,vec3.up()));
    if(index===path.length-1){this.playing=false;this.completedTask=this.selected;this.pulseUntil=getTime()+3;this.audio.play('clear',(this.selected==='door'?this.doorRoot:this.player).getTransform().getWorldPosition());this.menu='overview';this.updateActions();}
  }
  public suggest(id:string) {
    const target=Core.suggestedPositions[id];if(target)this.commitMove(id,target.x,target.y);
  }
  private commitMove(id:string,x:number,y:number,theta?:number) {
    const next=Core.moveObject(this.input.room,id,x,y,theta);
    if(next===this.input.room){const object=this.input.room.objects.find((o:any)=>o.id===id);this.present(object&&object.locked?object.name+' is locked. Its pose is preserved.':Core.placementIssue(this.input.room,id,x,y,theta)||'No change to this piece.');return;}
    const moved=next.objects.find((object:any)=>object.id===id);
    if(Core.objectPolygon(moved).some((p:any)=>p.x<0||p.y<0||p.x>next.width||p.y>next.depth)) {
      this.present('That edit crosses the room boundary. Choose another position.');return;
    }
    this.history.push(this.copy(this.input));this.input.room=next;this.evaluateCurrent();
  }
